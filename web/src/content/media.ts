/**
 * РЕЕСТР ИЗОБРАЖЕНИЙ САЙТА
 *
 * Как добавить или заменить картинку:
 *   1. Положи файл в папку web/public/images/.
 *   2. Пропиши путь в поле src ниже: `src: "/images/имя-файла.jpg"`.
 *   3. Всё. Картинка появится на сайте, заглушка исчезнет сама.
 *
 * Пока src: null — на месте картинки аккуратная фирменная заглушка.
 *
 * width/height — реальный размер файла в пикселях: по ним браузер заранее
 * резервирует место, и страница не «прыгает» при загрузке.
 *
 * Исходники фото — папка «Документы» (HEIC с телефона). На скриншотах уроков
 * размыты вкладки с именами учеников и окно видеосвязи: публиковать чужие
 * имена и лица без согласия нельзя.
 */

export type MediaSpec = {
  /** Путь к файлу в public/, или null если файла ещё нет. */
  src: string | null;
  /** Описание картинки: читают незрячие пользователи и поисковики. Заполнять обязательно. */
  alt: string;
  /** Ширина файла, px. */
  width: number;
  /** Высота файла, px. */
  height: number;
  /** Что должно быть на фото — подсказка для съёмки и подбора. */
  hint: string;
  /**
   * Куда смотреть при обрезке на узких экранах.
   * Для портрета почти всегда "top" — иначе на телефоне отрежет голову.
   */
  focus?: "center" | "top" | "bottom" | "left" | "right";
};

