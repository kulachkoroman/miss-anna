export type MediaKey = keyof typeof MEDIA;

/** Список незаполненных слотов — чтобы быстро понять, каких фото не хватает. */
export function missingMedia(): Array<{ key: MediaKey; spec: MediaSpec }> {
  return (Object.keys(MEDIA) as MediaKey[])
    .filter((key) => !MEDIA[key].src)
    .map((key) => ({ key, spec: MEDIA[key] }));
}

/**
 * Обложка курса.
 *
 * В отличие от остальных слотов путь приходит не отсюда, а из базы: обложку
 * Анна загружает через админку. Функция лишь приводит её к общему виду,
 * чтобы работал тот же <MediaSlot> с той же заглушкой.
 */
export function courseCoverSpec(course: {
  title: string;
  coverImage: string | null;
}): MediaSpec {
  return {
    src: course.coverImage,
    alt: `Обложка курса «${course.title}»`,
    width: 1600,
    height: 900,
    hint:
      "Горизонтальная обложка 16:9. Поверх ложится название курса, " +
      "поэтому мелкий текст и лица у нижнего края лучше не размещать.",
    focus: "center",
  };
}
